// Command gen-public-catalogs generates large public catalog facades from the
// pinned native Kusto.Language port.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
)

func main() {
	root, err := filepath.Abs("..")
	if err != nil {
		panic(err)
	}

	functionFields := catalogFields(filepath.Join(root, "kustolang", "engine", "functions_convert.go"), "functionSet")
	if len(functionFields) != 429 {
		panic(fmt.Errorf("function catalog field count = %d, want 429", len(functionFields)))
	}
	writeFunctionCatalog(root, functionFields)

	commandFields := catalogFields(filepath.Join(root, "kustolang", "engine", "engine_command_catalog_gen.go"), "engineCommandsSet")
	if len(commandFields) != 637 {
		panic(fmt.Errorf("engine command catalog field count = %d, want 637", len(commandFields)))
	}
	writeCommandCatalog(root, commandFields)
}

func writeFunctionCatalog(root string, fields []string) {
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by tools/gen-public-catalogs; DO NOT EDIT.")
	fmt.Fprintln(&output, "//")
	fmt.Fprintln(&output, "// The declarations mirror the Apache-2.0 licensed Microsoft Kusto.Language")
	fmt.Fprintln(&output, "// function catalog pinned in third_party/kusto/UPSTREAM.json.")
	fmt.Fprintln(&output, "package kustolang")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `import internal "github.com/olafhartong/kusto-lang-go/kustolang/engine"`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "// FunctionCatalog contains every public built-in scalar function symbol.")
	fmt.Fprintln(&output, "// All returns a defensive copy in pinned upstream order.")
	fmt.Fprintln(&output, "type FunctionCatalog struct {")
	for _, name := range fields {
		fmt.Fprintf(&output, "\t%s *FunctionSymbol\n", name)
	}
	fmt.Fprintln(&output, "\tall []*FunctionSymbol")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "var Functions = newFunctionCatalog()")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "func newFunctionCatalog() *FunctionCatalog {")
	fmt.Fprintln(&output, "\tsource := internal.Functions")
	fmt.Fprintln(&output, "\treturn &FunctionCatalog{")
	for _, name := range fields {
		fmt.Fprintf(&output, "\t\t%s: source.%s,\n", name, name)
	}
	fmt.Fprintln(&output, "\t\tall: append([]*FunctionSymbol{}, source.All...),")
	fmt.Fprintln(&output, "\t}")
	fmt.Fprintln(&output, "}")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "func (c *FunctionCatalog) All() []*FunctionSymbol {")
	fmt.Fprintln(&output, "\tif c == nil {")
	fmt.Fprintln(&output, "\t\treturn nil")
	fmt.Fprintln(&output, "\t}")
	fmt.Fprintln(&output, "\treturn append([]*FunctionSymbol{}, c.all...)")
	fmt.Fprintln(&output, "}")

	writeFormatted(filepath.Join(root, "kustolang", "functions_catalog_generated.go"), &output)
}

