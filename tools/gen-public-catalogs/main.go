func writeFormatted(path string, output *bytes.Buffer) {
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(fmt.Errorf("format generated source: %w\n%s", err, output.String()))
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		panic(err)
	}
}

func catalogFields(path, typeName string) []string {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		panic(err)
	}
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.TYPE {
			continue
		}
		for _, spec := range general.Specs {
			typeSpec := spec.(*ast.TypeSpec)
			if typeSpec.Name.Name != typeName {
				continue
			}
			structure, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				panic(fmt.Sprintf("%s is not a struct", typeName))
			}
			var names []string
			for _, field := range structure.Fields.List {
				for _, name := range field.Names {
					if name.Name != "All" {
						names = append(names, name.Name)
					}
				}
			}
			return names
		}
	}
	panic(fmt.Sprintf("%s type not found", typeName))
}
