package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	upstreamSourcePath = "src/Kusto.Language/Diagnostics/DiagnosticFacts.cs"
)

type upstreamMetadata struct {
	SourceFiles map[string]upstreamSourceFile `json:"source_files"`
}

type upstreamSourceFile struct {
	SnapshotFile string `json:"snapshot_file"`
	SHA256       string `json:"sha256"`
}

type factory struct {
	internalName string
	publicName   string
	parameters   string
	arguments    string
	position     token.Pos
}

func main() {
	check := flag.Bool("check", false, "verify that the generated file is current")
	rootFlag := flag.String("root", "", "repository root (auto-detected when omitted)")
	flag.Parse()
	root, err := resolveRoot(*rootFlag)
	if err != nil {
		fail(err)
	}
	sourcePath := filepath.Join(root, "kustolang", "engine", "diagnostic_facts.go")
	outputPath := filepath.Join(root, "kustolang", "diagnostic_facts_generated.go")

	upstreamFactories, upstreamDeclarations, upstreamHash, err := loadUpstreamFactories(root)
	if err != nil {
		fail(err)
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, sourcePath, nil, parser.SkipObjectResolution)
	if err != nil {
		fail(err)
	}

	var factories []factory
	seen := map[string]struct{}{}
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Recv != nil || !strings.HasPrefix(function.Name.Name, "Diagnostic") || !returnsDiagnostic(function) {
			continue
		}
		publicName := "DiagnosticFactsGet" + strings.TrimPrefix(function.Name.Name, "Diagnostic")
		if _, exists := seen[publicName]; exists {
			fail(fmt.Errorf("duplicate generated factory %s", publicName))
		}
		seen[publicName] = struct{}{}
		parameters, arguments, err := renderParameters(fset, function.Type.Params)
		if err != nil {
			fail(fmt.Errorf("render %s: %w", function.Name.Name, err))
		}
		factories = append(factories, factory{
			internalName: function.Name.Name,
			publicName:   publicName,
			parameters:   parameters,
			arguments:    arguments,
			position:     function.Pos(),
		})
	}
	sort.Slice(factories, func(i, j int) bool { return factories[i].position < factories[j].position })
	for upstreamName := range upstreamFactories {
		publicName := "DiagnosticFacts" + upstreamName
		if _, ok := seen[publicName]; !ok {
			fail(fmt.Errorf("pinned upstream factory %s has no generated Go facade", upstreamName))
		}
	}
	var sourceFactories []factory
	var compatibilityFactories []factory
	for _, factory := range factories {
		upstreamName := strings.TrimPrefix(factory.publicName, "DiagnosticFacts")
		if _, ok := upstreamFactories[upstreamName]; ok {
			sourceFactories = append(sourceFactories, factory)
		} else {
			compatibilityFactories = append(compatibilityFactories, factory)
		}
	}

	var generated bytes.Buffer
	generated.WriteString("// Code generated by tools/gen-public-diagnostic-facts; DO NOT EDIT.\n")
	generated.WriteString("//\n")
	generated.WriteString("// Ported from src/Kusto.Language/Diagnostics/DiagnosticFacts.cs.\n")
	fmt.Fprintf(&generated, "// Pinned source SHA-256: %s.\n", upstreamHash)
	generated.WriteString("// See third_party/kusto/LICENSE for the preserved Apache-2.0 license.\n\n")
	generated.WriteString("package kustolang\n\n")
	generated.WriteString("import internal \"github.com/olafhartong/kusto-lang-go/kustolang/engine\"\n\n")
	fmt.Fprintf(&generated, "const (\n")
	fmt.Fprintf(&generated, "\tDiagnosticFactsFactoryCount = %d\n", len(factories))
	fmt.Fprintf(&generated, "\tDiagnosticFactsUpstreamDeclarationCount = %d\n", upstreamDeclarations)
	fmt.Fprintf(&generated, "\tDiagnosticFactsUpstreamFactoryCount = %d\n", len(upstreamFactories))
	fmt.Fprintf(&generated, "\tDiagnosticFactsCompatibilityFactoryCount = %d\n", len(compatibilityFactories))
	fmt.Fprintf(&generated, "\tDiagnosticFactsUpstreamSourceSHA256 = %q\n", upstreamHash)
	fmt.Fprintf(&generated, ")\n\n")
	for _, factory := range sourceFactories {
		writeFactory(&generated, factory)
	}
	generated.WriteString("// Compatibility factories preserve internal diagnostics and source-spelling aliases.\n\n")
	for _, factory := range compatibilityFactories {
		writeFactory(&generated, factory)
	}
	generated.WriteString("func DiagnosticFactsCompatibilityFactoryNames() []string {\n")
	generated.WriteString("\treturn []string{\n")
	for _, factory := range compatibilityFactories {
		fmt.Fprintf(&generated, "\t\t%q,\n", factory.publicName)
	}
	generated.WriteString("\t}\n")
	generated.WriteString("}\n")

	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		fail(fmt.Errorf("format generated source: %w\n%s", err, generated.Bytes()))
	}
	if *check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			fail(err)
		}
		if !bytes.Equal(current, formatted) {
			fail(fmt.Errorf("%s is not current; run go generate ./kustolang", outputPath))
		}
		return
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		fail(err)
	}
}

func writeFactory(generated *bytes.Buffer, factory factory) {
	fmt.Fprintf(generated, "func %s(%s) Diagnostic {\n", factory.publicName, factory.parameters)
	fmt.Fprintf(generated, "\treturn internal.%s(%s)\n", factory.internalName, factory.arguments)
	generated.WriteString("}\n\n")
}

func loadUpstreamFactories(root string) (map[string]struct{}, int, string, error) {
	upstreamPath := filepath.Join(root, "third_party", "kusto", "UPSTREAM.json")
	data, err := os.ReadFile(upstreamPath)
	if err != nil {
		return nil, 0, "", err
	}
	var metadata upstreamMetadata
	if err := json.Unmarshal(data, &metadata); err != nil {
		return nil, 0, "", err
	}
	sourceFile, ok := metadata.SourceFiles[upstreamSourcePath]
	if !ok || sourceFile.SnapshotFile == "" || sourceFile.SHA256 == "" {
		return nil, 0, "", fmt.Errorf("%s does not pin %s", upstreamPath, upstreamSourcePath)
	}
	snapshotPath := filepath.Join(root, filepath.FromSlash(sourceFile.SnapshotFile))
	source, err := os.ReadFile(snapshotPath)
	if err != nil {
		return nil, 0, "", err
	}
	actualHash := fmt.Sprintf("%x", sha256.Sum256(source))
	if actualHash != sourceFile.SHA256 {
		return nil, 0, "", fmt.Errorf("pinned %s hash mismatch: manifest %s, actual %s", upstreamSourcePath, sourceFile.SHA256, actualHash)
	}
	tokens, err := csharpTokens(source)
	if err != nil {
		return nil, 0, "", err
	}
	factories := make(map[string]struct{})
	declarations := 0
	for i := 0; i+4 < len(tokens); i++ {
		if isDiagnosticFactoryDeclaration(tokens, i) {
			factories[tokens[i+3]] = struct{}{}
			declarations++
		}
	}
	if declarations == 0 {
		return nil, 0, "", fmt.Errorf("no public DiagnosticFacts declarations found in %s", snapshotPath)
	}
	return factories, declarations, actualHash, nil
}

func resolveRoot(explicit string) (string, error) {
	if explicit != "" {
		if _, err := os.Stat(filepath.Join(explicit, "go.mod")); err != nil {
			return "", fmt.Errorf("repository root %q: %w", explicit, err)
		}
		return explicit, nil
	}
	for _, candidate := range []string{".", ".."} {
		if _, err := os.Stat(filepath.Join(candidate, "go.mod")); err == nil {
			return candidate, nil
		}
	}
	return "", fmt.Errorf("could not locate repository root")
}

func isDiagnosticFactoryDeclaration(tokens []string, start int) bool {
	if start+4 >= len(tokens) || tokens[start] != "public" || tokens[start+1] != "static" || tokens[start+2] != "Diagnostic" || !strings.HasPrefix(tokens[start+3], "Get") {
		return false
	}
	next := start + 4
	if tokens[next] == "<" {
		depth := 0
		for next < len(tokens) {
			switch tokens[next] {
			case "<":
				depth++
			case ">":
				depth--
				if depth == 0 {
					next++
					return next < len(tokens) && tokens[next] == "("
				}
			}
			next++
		}
		return false
	}
	return tokens[next] == "("
}

func csharpTokens(source []byte) ([]string, error) {
	var tokens []string
	for i := 0; i < len(source); {
		switch {
		case source[i] == ' ' || source[i] == '\t' || source[i] == '\r' || source[i] == '\n':
			i++
		case i+1 < len(source) && source[i] == '/' && source[i+1] == '/':
			i += 2
			for i < len(source) && source[i] != '\n' {
				i++
			}
		case i+1 < len(source) && source[i] == '/' && source[i+1] == '*':
			i += 2
			for i+1 < len(source) && (source[i] != '*' || source[i+1] != '/') {
				i++
			}
			if i+1 >= len(source) {
				return nil, fmt.Errorf("unterminated C# block comment")
			}
			i += 2
		case source[i] == '"' || source[i] == '\'':
			quote := source[i]
			i++
			closed := false
			for i < len(source) {
				if source[i] == '\\' {
					i += 2
					continue
				}
				if source[i] == quote {
					i++
					closed = true
					break
				}
				i++
			}
			if !closed {
				return nil, fmt.Errorf("unterminated C# literal")
			}
		case isIdentifierStart(source[i]):
			start := i
			i++
			for i < len(source) && isIdentifierPart(source[i]) {
				i++
			}
			tokens = append(tokens, string(source[start:i]))
		default:
			tokens = append(tokens, string(source[i]))
			i++
		}
	}
	return tokens, nil
}

func isIdentifierStart(ch byte) bool {
	return ch == '_' || ch >= 'A' && ch <= 'Z' || ch >= 'a' && ch <= 'z'
}

func isIdentifierPart(ch byte) bool {
	return isIdentifierStart(ch) || ch >= '0' && ch <= '9'
}

func returnsDiagnostic(function *ast.FuncDecl) bool {
	return function.Type.Results != nil && len(function.Type.Results.List) == 1 && isIdentifier(function.Type.Results.List[0].Type, "Diagnostic")
}

func isIdentifier(expression ast.Expr, name string) bool {
	identifier, ok := expression.(*ast.Ident)
	return ok && identifier.Name == name
}

func renderParameters(fset *token.FileSet, fields *ast.FieldList) (string, string, error) {
	if fields == nil || len(fields.List) == 0 {
		return "", "", nil
	}
	var parameters []string
	var arguments []string
	for _, field := range fields.List {
		if len(field.Names) == 0 {
			return "", "", fmt.Errorf("unnamed parameter")
		}
		var typeText bytes.Buffer
		if err := format.Node(&typeText, fset, field.Type); err != nil {
			return "", "", err
		}
		names := make([]string, len(field.Names))
		for i, name := range field.Names {
			names[i] = name.Name
			argument := name.Name
			if _, variadic := field.Type.(*ast.Ellipsis); variadic && i == len(field.Names)-1 {
				argument += "..."
			}
			arguments = append(arguments, argument)
		}
		parameters = append(parameters, strings.Join(names, ", ")+" "+typeText.String())
	}
	return strings.Join(parameters, ", "), strings.Join(arguments, ", "), nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
