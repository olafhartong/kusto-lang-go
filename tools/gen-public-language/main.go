// Command gen-public-language generates the public syntax-node and SyntaxKind
// aliases from the pinned native Kusto.Language port.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
)

var allowAPIExpansion = flag.Bool("allow-api-expansion", false, "allow new declarations in the generated public facade")

func main() {
	flag.Parse()
	root, err := filepath.Abs("..")
	if err != nil {
		panic(err)
	}
	internalDir := filepath.Join(root, "kustolang", "engine")

	nodeNames := exportedTypeNames(filepath.Join(internalDir, "generated_nodes_types_gen.go"))
	nodeNames = append(nodeNames, exportedTypeNames(filepath.Join(internalDir, "generated_visitors_gen.go"))...)
	constructors := exportedFunctionsWithPrefixes(filepath.Join(internalDir, "generated_nodes_types_gen.go"), "New", "MustNew")
	kindNames := exportedConstNames(filepath.Join(internalDir, "syntax_kind.go"))
	diagnosticFunctions := exportedFunctions(filepath.Join(internalDir, "diagnostic_facts.go"), "Diagnostic")
	publicPath := filepath.Join(root, "kustolang", "language_generated.go")
	if !*allowAPIExpansion {
		nodeNames = retainTypes(nodeNames, typeNameSet(exportedTypeNames(publicPath)))
		allowedFunctions := functionNameSet(exportedFunctionsWithPrefixes(publicPath, ""))
		constructors = retainFunctions(constructors, allowedFunctions)
		diagnosticFunctions = retainFunctions(diagnosticFunctions, allowedFunctions)
		kindNames = retainNames(kindNames, nameSet(exportedConstNames(publicPath)))
	}

	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by tools/gen-public-language; DO NOT EDIT.")
	fmt.Fprintln(&output, "//")
	fmt.Fprintln(&output, "// The declarations mirror the Apache-2.0 licensed Microsoft Kusto.Language")
	fmt.Fprintln(&output, "// syntax model pinned in third_party/kusto/UPSTREAM.json.")
	fmt.Fprintln(&output, "package kustolang")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `import internal "github.com/olafhartong/kusto-lang-go/kustolang/engine"`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "// Generated syntax-node aliases preserve the concrete typed AST returned by the parser.")
	fmt.Fprintln(&output, "type (")
	for _, typ := range nodeNames {
		fmt.Fprintf(&output, "\t%s%s = internal.%s%s\n", typ.name, typ.parameters, typ.name, typ.arguments)
	}
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "// Generated constructors provide typed AST construction without exposing internal packages.")
	for _, function := range constructors {
		fmt.Fprintf(&output, "func %s%s(%s) %s {\n", function.name, function.typeParameters, function.parameters, function.results)
		fmt.Fprintf(&output, "\treturn internal.%s(%s)\n", function.name, function.arguments)
		fmt.Fprintln(&output, "}")
	}
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "// Diagnostic factories retain the pinned upstream codes and messages.")
	for _, function := range diagnosticFunctions {
		fmt.Fprintf(&output, "func %s(%s) Diagnostic {\n", function.name, function.parameters)
		fmt.Fprintf(&output, "\treturn internal.%s(%s)\n", function.name, function.arguments)
		fmt.Fprintln(&output, "}")
	}
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "// SyntaxKind constants are generated from the same pinned catalog as the parser.")
	fmt.Fprintln(&output, "const (")
	for _, name := range kindNames {
		fmt.Fprintf(&output, "\t%s = internal.%s\n", name, name)
	}
	fmt.Fprintln(&output, ")")

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(fmt.Errorf("format generated source: %w\n%s", err, output.String()))
	}
	if err := os.WriteFile(publicPath, formatted, 0o644); err != nil {
		panic(err)
	}
}

type exportedType struct {
	name       string
	parameters string
	arguments  string
}

func typeNameSet(types []exportedType) map[string]bool {
	names := make(map[string]bool, len(types))
	for _, typ := range types {
		names[typ.name] = true
	}
	return names
}

func retainTypes(types []exportedType, allowed map[string]bool) []exportedType {
	result := make([]exportedType, 0, len(types))
	for _, typ := range types {
		if allowed[typ.name] {
			result = append(result, typ)
		}
	}
	return result
}

func exportedTypeNames(path string) []exportedType {
	file := parseFile(path)
	var names []exportedType
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.TYPE {
			continue
		}
		for _, spec := range general.Specs {
			typeSpec := spec.(*ast.TypeSpec)
			if ast.IsExported(typeSpec.Name.Name) {
				typ := exportedType{name: typeSpec.Name.Name}
				if typeSpec.TypeParams != nil {
					var parameters bytes.Buffer
					var arguments bytes.Buffer
					parameters.WriteByte('[')
					arguments.WriteByte('[')
					first := true
					for _, field := range typeSpec.TypeParams.List {
						for nameIndex, parameterName := range field.Names {
							if !first {
								parameters.WriteString(", ")
								arguments.WriteString(", ")
							}
							first = false
							parameters.WriteString(parameterName.Name)
							if nameIndex == len(field.Names)-1 {
								parameters.WriteByte(' ')
								if err := printer.Fprint(&parameters, token.NewFileSet(), field.Type); err != nil {
									panic(err)
								}
							}
							arguments.WriteString(parameterName.Name)
						}
					}
					parameters.WriteByte(']')
					arguments.WriteByte(']')
					typ.parameters = parameters.String()
					typ.arguments = arguments.String()
				}
				names = append(names, typ)
			}
		}
	}
	return names
}

func exportedConstNames(path string) []string {
	file := parseFile(path)
	var names []string
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}
		for _, spec := range general.Specs {
			valueSpec := spec.(*ast.ValueSpec)
			for _, name := range valueSpec.Names {
				if ast.IsExported(name.Name) {
					names = append(names, name.Name)
				}
			}
		}
	}
	return names
}

type exportedFunction struct {
	name           string
	typeParameters string
	parameters     string
	arguments      string
	results        string
}

func functionNameSet(functions []exportedFunction) map[string]bool {
	names := make(map[string]bool, len(functions))
	for _, function := range functions {
		names[function.name] = true
	}
	return names
}

func retainFunctions(functions []exportedFunction, allowed map[string]bool) []exportedFunction {
	result := make([]exportedFunction, 0, len(functions))
	for _, function := range functions {
		if allowed[function.name] {
			result = append(result, function)
		}
	}
	return result
}

func nameSet(values []string) map[string]bool {
	names := make(map[string]bool, len(values))
	for _, value := range values {
		names[value] = true
	}
	return names
}

func retainNames(values []string, allowed map[string]bool) []string {
	result := make([]string, 0, len(values))
	for _, value := range values {
		if allowed[value] {
			result = append(result, value)
		}
	}
	return result
}

func exportedFunctions(path, prefix string) []exportedFunction {
	return exportedFunctionsWithPrefixes(path, prefix)
}

func exportedFunctionsWithPrefixes(path string, prefixes ...string) []exportedFunction {
	file := parseFile(path)
	var functions []exportedFunction
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Recv != nil || !ast.IsExported(function.Name.Name) || !hasPrefix(function.Name.Name, prefixes) {
			continue
		}
		var parameters bytes.Buffer
		var arguments bytes.Buffer
		first := true
		for _, field := range function.Type.Params.List {
			if len(field.Names) == 0 {
				panic(fmt.Sprintf("exported function %s has an unnamed parameter", function.Name.Name))
			}
			for nameIndex, name := range field.Names {
				if !first {
					parameters.WriteString(", ")
					arguments.WriteString(", ")
				}
				first = false
				parameters.WriteString(name.Name)
				if nameIndex == len(field.Names)-1 {
					parameters.WriteByte(' ')
					if err := printer.Fprint(&parameters, token.NewFileSet(), field.Type); err != nil {
						panic(err)
					}
				}
				arguments.WriteString(name.Name)
				if _, variadic := field.Type.(*ast.Ellipsis); variadic && nameIndex == len(field.Names)-1 {
					arguments.WriteString("...")
				}
			}
		}
		functions = append(functions, exportedFunction{
			name:           function.Name.Name,
			typeParameters: formatTypeParameters(function.Type.TypeParams),
			parameters:     parameters.String(),
			arguments:      arguments.String(),
			results:        formatResults(function.Type.Results),
		})
	}
	return functions
}

func hasPrefix(name string, prefixes []string) bool {
	for _, prefix := range prefixes {
		if len(name) >= len(prefix) && name[:len(prefix)] == prefix {
			return true
		}
	}
	return false
}

func formatTypeParameters(fields *ast.FieldList) string {
	if fields == nil {
		return ""
	}
	var output bytes.Buffer
	output.WriteByte('[')
	for fieldIndex, field := range fields.List {
		if fieldIndex > 0 {
			output.WriteString(", ")
		}
		for nameIndex, name := range field.Names {
			if nameIndex > 0 {
				output.WriteString(", ")
			}
			output.WriteString(name.Name)
		}
		if len(field.Names) > 0 {
			output.WriteByte(' ')
		}
		if err := printer.Fprint(&output, token.NewFileSet(), field.Type); err != nil {
			panic(err)
		}
	}
	output.WriteByte(']')
	return output.String()
}

func formatResults(fields *ast.FieldList) string {
	if fields == nil || len(fields.List) == 0 {
		return ""
	}
	if len(fields.List) == 1 && len(fields.List[0].Names) == 0 {
		var output bytes.Buffer
		if err := printer.Fprint(&output, token.NewFileSet(), fields.List[0].Type); err != nil {
			panic(err)
		}
		return output.String()
	}
	var output bytes.Buffer
	output.WriteByte('(')
	first := true
	for _, field := range fields.List {
		if len(field.Names) == 0 {
			if !first {
				output.WriteString(", ")
			}
			first = false
			if err := printer.Fprint(&output, token.NewFileSet(), field.Type); err != nil {
				panic(err)
			}
			continue
		}
		for _, name := range field.Names {
			if !first {
				output.WriteString(", ")
			}
			first = false
			output.WriteString(name.Name)
			output.WriteByte(' ')
			if err := printer.Fprint(&output, token.NewFileSet(), field.Type); err != nil {
				panic(err)
			}
		}
	}
	output.WriteByte(')')
	return output.String()
}

func parseFile(path string) *ast.File {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		panic(err)
	}
	return file
}
